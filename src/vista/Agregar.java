    private void jButtonValidarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonValidarActionPerformed
        
        
        if(jComboBoxCategoría.getSelectedItem () != null){
        
            jLabelcategoriavalidar.setText("La Categoría es correcta");
            jLabelcategoriavalidar.setForeground(green);
            validacionCategoria = true;
        
        } else {
        
            jLabelcategoriavalidar.setText("Debe elegir una categoría válida");
            jLabelcategoriavalidar.setForeground(red);
            validacionCategoria = false;
            
        }
        
        if(!jTextFieldNombre.getText().isEmpty()) {
        
            jLabelnombrevalidar.setText("El nombre es válido");
            jLabelnombrevalidar.setForeground(green);           
            validacionNombre = true;
            
        } else {
        
            jLabelnombrevalidar.setText("Ingrese un nombre válido");
            jLabelnombrevalidar.setForeground(red);
            validacionNombre = false;            

        }
        
         if(!jTextFieldPrecio.getText().isEmpty()) {
        
            jLabelpreciovalidar.setText("El precio es válido");
            jLabelpreciovalidar.setForeground(green);           
            validacionPrecio = true;
         
        } else {
        
            jLabelpreciovalidar.setText("Ingrese un precio válido");
            jLabelpreciovalidar.setForeground(red);
              validacionPrecio = false;
              
        }
         
         if(!jTextFieldStock.getText().isEmpty()) {
        
            jLabelstockvalidar.setText("El stock es válido");
            jLabelstockvalidar.setForeground(green);           
            validacionStock = true;
            
        } else {
        
            jLabelstockvalidar.setText("Ingrese un stock válido");
            jLabelstockvalidar.setForeground(red);
            validacionStock = false;
            
         }        
         
         if(validacionCategoria && validacionNombre && validacionPrecio && validacionStock ==true){
         
             jButtonAgregar.setVisible(true);
             jLabel2.setText("Deberá seleccionar una imagen al momento de agregar los datos*");
         
         } else {
         
             jButtonAgregar.setVisible(false);
             
         }
        
    }//GEN-LAST:event_jButtonValidarActionPerformed

