    private void jButtonAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAgregarActionPerformed
         
        JFileChooser fch = new JFileChooser();
        fch.setFileSelectionMode(JFileChooser.FILES_AND_DIRECTORIES);
        FileNameExtensionFilter filtro1 = new FileNameExtensionFilter("*.PNG", "png");
        fch.setFileFilter(filtro1);
        int seleccion = fch.showOpenDialog(this);
        
        if (seleccion == JFileChooser.APPROVE_OPTION) {

            imag = fch.getSelectedFile();
        
        try (FileInputStream fis = new FileInputStream(imag);
             ByteArrayOutputStream bos = new ByteArrayOutputStream()) {

            byte[] buffer = new byte[1024];
            int bytesRead;

            while ((bytesRead = fis.read(buffer)) != -1) {
                bos.write(buffer, 0, bytesRead);
            }

            fileBytes = bos.toByteArray();
        }   catch (FileNotFoundException ex) {
                Logger.getLogger(Agregar.class.getName()).log(Level.SEVERE, null, ex);
            } catch (IOException ex) {
                Logger.getLogger(Agregar.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
        
        
        
        String item = String.valueOf(jComboBoxCategoría.getSelectedItem());
        String nomb = jTextFieldNombre.getText(); 
        int prec =  Integer.parseInt(jTextFieldPrecio.getText());
        int stock = Integer.parseInt(jTextFieldStock.getText());
        
        if(item=="Bebida"){
        
            Bebidas bebida1 = new Bebidas(item, nomb, prec, stock, fileBytes);
            bebida1.imprimir();
            m1.Agregar(bebida1);
            jDialog1.setSize(464, 340);
            jDialog1.setLocation(600, 300);
            jDialog1.show();
            
        } else if(item=="Comida") {
        
            Comidas comida1 = new Comidas(item, nomb, prec, stock, fileBytes);
            comida1.imprimir();
            m1.Agregar(comida1);
            jDialog1.setSize(464, 340);
            jDialog1.setLocation(600, 300);
            jDialog1.show();
        }
        
    }//GEN-LAST:event_jButtonAgregarActionPerformed

